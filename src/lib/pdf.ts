import type { Invoice, Organization } from "@shared/types";
import { formatMoney, lineAmount } from "@shared/money";
import { formatDate } from "@shared/dates";

/** Generate an invoice PDF in the browser (no data leaves the device). */
export async function invoicePdf(inv: Invoice, org: Organization, opts: { sample?: boolean } = {}) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const m = (v: number) => formatMoney(v, inv.currency);
  const tz = org.timezone;

  if (opts.sample) {
    doc.setTextColor(230, 160, 20);
    doc.setFontSize(9);
    doc.text("SAMPLE INVOICE — DEMO MODE — NOT A REQUEST FOR PAYMENT", W / 2, 24, { align: "center" });
  }
  doc.setFillColor(16, 185, 129);
  doc.roundedRect(40, 44, 26, 26, 6, 6, "F");
  doc.setTextColor(20, 24, 26);
  doc.setFontSize(18);
  doc.setFont("helvetica", "bold");
  doc.text(org.name, 76, 63);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(110, 118, 124);
  [org.address, org.email, org.website].filter(Boolean).forEach((l, i) => doc.text(String(l), 76, 78 + i * 12));

  doc.setFontSize(24);
  doc.setTextColor(20, 24, 26);
  doc.setFont("helvetica", "bold");
  doc.text("INVOICE", W - 40, 63, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(110, 118, 124);
  const meta: [string, string][] = [
    ["Invoice #", inv.number],
    ["Issued", formatDate(inv.issueDate, tz)],
    ["Due", formatDate(inv.dueDate, tz)],
    ["Terms", inv.terms],
  ];
  meta.forEach(([k, v], i) => {
    doc.text(k, W - 160, 82 + i * 13);
    doc.setTextColor(20, 24, 26);
    doc.text(v, W - 40, 82 + i * 13, { align: "right" });
    doc.setTextColor(110, 118, 124);
  });

  doc.setFontSize(8);
  doc.text("BILL TO", 40, 150);
  doc.setFontSize(11);
  doc.setTextColor(20, 24, 26);
  doc.text(inv.customerName, 40, 166);
  doc.setFontSize(9);
  doc.setTextColor(110, 118, 124);
  doc.text(inv.customerEmail, 40, 179);

  autoTable(doc, {
    startY: 205,
    head: [["Description", "Qty", "Unit price", "Tax", "Amount"]],
    body: inv.lines.map((l) => [l.description, String(l.quantity), m(l.unitPrice), l.taxRate ? `${l.taxRate}%` : "—", m(lineAmount(l))]),
    styles: { fontSize: 9, cellPadding: 7, textColor: [30, 34, 36] },
    headStyles: { fillColor: [245, 247, 248], textColor: [110, 118, 124], fontStyle: "normal" },
    columnStyles: { 1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" }, 4: { halign: "right" } },
    margin: { left: 40, right: 40 },
  });
  let y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 20;
  const t = inv.totals;
  const rows: [string, string, boolean?][] = [
    ["Subtotal", m(t.subtotal)],
    ...(t.discount ? ([["Discount", `−${m(t.discount)}`]] as [string, string][]) : []),
    ["Tax", m(t.tax)],
    ["Total", m(t.total), true],
    ...(t.paid ? ([["Paid", `−${m(t.paid)}`], ["Balance due", m(t.balance), true]] as [string, string, boolean][]) : []),
  ];
  for (const [k, v, bold] of rows) {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setFontSize(bold ? 11 : 9);
    doc.setTextColor(bold ? 20 : 110, bold ? 24 : 118, bold ? 26 : 124);
    doc.text(k, W - 200, y);
    doc.text(v, W - 40, y, { align: "right" });
    y += bold ? 18 : 14;
  }
  if (inv.notes) {
    y += 16;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(110, 118, 124);
    doc.text("NOTES", 40, y);
    doc.setFontSize(9);
    doc.setTextColor(30, 34, 36);
    doc.text(doc.splitTextToSize(inv.notes, W - 80), 40, y + 13);
  }
  doc.setFontSize(8);
  doc.setTextColor(150, 156, 160);
  doc.text(`Generated by PayPilot · ${inv.currency}`, 40, doc.internal.pageSize.getHeight() - 30);
  doc.save(`${inv.number}${opts.sample ? "-SAMPLE" : ""}.pdf`);
}
